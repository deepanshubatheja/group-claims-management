import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const packageJson = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));
const generatedPaths = [
  "frontend/src/generated-build-metadata.ts",
  "electron/src/generated-build-metadata.ts",
  "backend/group_claims_backend/generated_build_metadata.py",
];

function git(arguments_) {
  try {
    return execFileSync("git", arguments_, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return "";
  }
}

function snapshot() {
  const exclusions = generatedPaths.map((item) => `:(exclude)${item}`);
  const diff = git(["diff", "--binary", "HEAD", "--", ".", ...exclusions]);
  const status = git(["status", "--porcelain=v1", "--untracked-files=all", "--", ".", ...exclusions]);
  const untrackedContent = status.split("\n").filter((line) => line.startsWith("?? ")).map((line) => line.slice(3)).sort().map((relative) => {
    try {
      return `${relative}\0${createHash("sha256").update(readFileSync(path.join(root, relative))).digest("hex")}`;
    } catch {
      return `${relative}\0unreadable`;
    }
  }).join("\n");
  return { dirty: Boolean(diff || status), hash: createHash("sha256").update(`${diff}\n${status}\n${untrackedContent}`).digest("hex") };
}

const revision = git(["rev-parse", "HEAD"]) || "unknown";
const source = snapshot();
const buildDate = new Date().toISOString();
const sourceState = source.dirty ? `dirty-${source.hash.slice(0, 12)}` : "clean";
const metadata = {
  applicationVersion: packageJson.version,
  buildDate,
  sourceRevision: revision,
  sourceRevisionShort: revision.slice(0, 12),
  sourceState,
  buildId: `claimflow-${packageJson.version}-g${revision.slice(0, 12)}-${sourceState}-${buildDate.replace(/[-:.]/g, "")}`,
};
const ts = `/** Generated by scripts/generate-build-metadata.mjs. */\nexport const BUILD_METADATA = Object.freeze(${JSON.stringify(metadata, null, 2)} as const);\n`;
const py = `\"\"\"Generated by scripts/generate-build-metadata.mjs.\"\"\"\n\nBUILD_METADATA = ${JSON.stringify(metadata, null, 2)}\n`;
for (const relative of generatedPaths.slice(0, 2)) writeFileSync(path.join(root, relative), ts, "utf8");
writeFileSync(path.join(root, generatedPaths[2]), py, "utf8");
process.stdout.write(`${metadata.buildId}\n`);
